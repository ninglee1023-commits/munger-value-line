function markdownHeadings(markdown) {
  const result = [];
  let index = 0;
  String(markdown || "").split(/\r?\n/).forEach(function(line) {
    const match = line.trim().match(/^(#{1,2})\s+(.+)$/);
    if (!match) return;
    const title = match[2].replace(/\*\*/g,"").trim();
    if (title) result.push({id:"md-" + index,title:title});
    index += 1;
  });
  return result;
}

function renderMarkdown(markdown, sources, assetBase) {
  const lines = String(markdown || "").split(/\r?\n/);
  let html = "";
  let i = 0;
  let headingIndex = 0;
  while (i < lines.length) {
    const line = lines[i].trim();
    if (!line) { i += 1; continue; }
    const picture = line.match(/^!\[([^\]]*)\]\(([^\s)]+)\)$/);
    if (picture) {
      const src = safeImageUrl(picture[2],assetBase);
      if (src) html += '<div class="report-image"><img src="' + esc(src) + '" alt="' + esc(picture[1]) + '" style="display:block;max-width:100%;height:auto" /></div>';
      else html += '<p>' + esc(line) + '</p>';
      i += 1; continue;
    }
    const heading = line.match(/^(#{1,3})\s+(.+)$/);
    if (heading) {
      if (heading[1].length === 3) {
        html += '<h3 class="emphasis-line">' + inlineRich(heading[2], sources) + "</h3>";
      } else {
        html += '<h2 id="md-' + headingIndex + '">' + inlineRich(heading[2], sources) + "</h2>";
        headingIndex += 1;
      }
      i += 1; continue;
    }
    if (/^---+$/.test(line)) { html += "<hr/>"; i += 1; continue; }
    if (line.startsWith(">")) {
      const quote = [];
      while (i < lines.length && lines[i].trim().startsWith(">")) {
        quote.push(lines[i].trim().replace(/^>\s?/,"")); i += 1;
      }
      html += "<blockquote>" + quote.map(function(x) { return inlineRich(x,sources); }).join("<br>") + "</blockquote>";
      continue;
    }
    if (line.startsWith("|") && i + 1 < lines.length && /^\|?[\s:|-]+\|/.test(lines[i+1].trim())) {
      const rows = [];
      while (i < lines.length && lines[i].trim().startsWith("|")) {
        rows.push(lines[i].trim().replace(/^\||\|$/g,"").split("|").map(function(x){ return x.trim(); }));
        i += 1;
      }
      const headers = rows.shift() || [];
      rows.shift();
      html += renderTable({headers:headers,rows:rows}, sources);
      continue;
    }
    if (/^[-*]\s+/.test(line)) {
      const items = [];
      while (i < lines.length && /^[-*]\s+/.test(lines[i].trim())) {
        items.push(lines[i].trim().replace(/^[-*]\s+/,"")); i += 1;
      }
      html += "<ul>" + items.map(function(x){ return "<li>" + inlineRich(x,sources) + "</li>"; }).join("") + "</ul>";
      continue;
    }
    if (/^\d+[.)]\s+/.test(line)) {
      const start = Number(line.match(/^(\d+)/)[1]);
      const items = [];
      while (i < lines.length && /^\d+[.)]\s+/.test(lines[i].trim())) {
        items.push(lines[i].trim().replace(/^\d+[.)]\s+/,"")); i += 1;
      }
      html += '<ol start="' + start + '">' + items.map(function(x){ return "<li>" + inlineRich(x,sources) + "</li>"; }).join("") + "</ol>";
      continue;
    }
    const paragraph = [line];
    i += 1;
    while (i < lines.length && lines[i].trim() && !/^(#{1,3})\s+/.test(lines[i].trim()) && !lines[i].trim().startsWith("![") && !lines[i].trim().startsWith("|") && !lines[i].trim().startsWith(">") && !/^[-*]\s+/.test(lines[i].trim()) && !/^\d+[.)]\s+/.test(lines[i].trim()) && !/^---+$/.test(lines[i].trim())) {
      paragraph.push(lines[i].trim()); i += 1;
    }
    html += "<p>" + paragraph.map(function(x){ return inlineRich(x,sources); }).join("<br>") + "</p>";
  }
  return html;
}

function tocHTML(items) {
  if (!items.length) return "";
  return '<details class="toc" open><summary>文章导航</summary><nav>' +
    items.map(function(item) { return '<a href="#' + esc(item.id) + '">' + esc(item.title) + "</a>"; }).join("") +
    "</nav></details>";
}

function structuredBody(report, sources) {
  let items = [];
  let html = "";
  if (report.history) {
    items.push({id:"history",title:report.history.title || "长期数据"});
    html += '<section class="report-section" id="history"><h2>' + esc(report.history.title || "长期数据") + "</h2>" + renderTable(report.history,sources) + "</section>";
  }
  (report.sections || []).forEach(function(section,index) {
    const id = "section-" + index;
    items.push({id:id,title:section.title});
    html += '<section class="report-section" id="' + id + '"><h2>' + inlineRich(section.title,sources) + "</h2>";
    (section.paragraphs || []).forEach(function(p) { html += "<p>" + inlineRich(p,sources) + "</p>"; });
    if (section.table) html += renderTable(section.table,sources);
    (section.tables || []).forEach(function(t) { html += renderTable(t,sources); });
    html += "</section>";
  });
  return {items:items,html:html};
}

